import { BriefOutput, ScopeOutput } from "../lib/types";

export function formatBriefAsText(brief: BriefOutput) {
  return [
    `PROJECT BRIEF`,
    `=============`,
    ``,
    `Summary:`,
    brief.project_summary,
    ``,
    `Client Problem:`,
    brief.client_problem,
    ``,
    `Desired Outcome:`,
    brief.desired_outcome,
    ``,
    `Key Deliverables:`,
    ...brief.key_deliverables.map((d) => `• ${d}`),
    ``,
    `Assumptions:`,
    ...brief.assumptions.map((a) => `• ${a}`),
    ``,
    `Missing Information:`,
    ...brief.missing_information.map((m) => `• ${m}`),
    ``,
    `Questions to Ask Client:`,
    ...brief.questions_to_ask.map((q) => `• ${q}`),
    ``,
    `Risks / Red Flags:`,
    ...brief.risks.map((r) => `• ${r}`),
    ``,
    `Recommended Next Step:`,
    brief.recommended_next_step,
    ``,
    `---`,
    `Generated by FreelanceOS`,
  ].join("\n");
}

export function formatScopeAsText(scope: ScopeOutput) {
  return [
    `SCOPE OF WORK`,
    `=============`,
    ``,
    `In-Scope:`,
    ...scope.in_scope.map((s) => `• ${s}`),
    ``,
    `Out-of-Scope:`,
    ...scope.out_of_scope.map((s) => `• ${s}`),
    ``,
    `Milestones:`,
    ...scope.milestones.map((m) => `• ${m}`),
    ``,
    `Client Responsibilities:`,
    ...scope.client_responsibilities.map((r) => `• ${r}`),
    ``,
    `Acceptance Criteria:`,
    ...scope.acceptance_criteria.map((c) => `• ${c}`),
    ``,
    `Revision Limits:`,
    scope.revision_limits,
    ``,
    `---`,
    `Generated by FreelanceOS`,
  ].join("\n");
}
